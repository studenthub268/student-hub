/**
 * Writes lib/generated/deploy-version.ts with the current deploy id:
 * the git short SHA on Vercel (VERCEL_GIT_COMMIT_SHA) or locally, else a
 * timestamp. Runs automatically before every `next build` (see the build
 * script in package.json). /api/version serves this id and the client
 * DeployWatcher uses it to refresh open pages when a new deploy lands.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const outPath = resolve(process.cwd(), "lib/generated/deploy-version.ts");

let version;
if (process.env.VERCEL_GIT_COMMIT_SHA) {
  version = process.env.VERCEL_GIT_COMMIT_SHA.slice(0, 12);
} else {
  try {
    version = execSync("git rev-parse --short=12 HEAD", { encoding: "utf8" }).trim();
  } catch {
    version = `t-${Date.now()}`;
  }
}

const content = `// AUTO-GENERATED by scripts/write-deploy-version.mjs — do not edit.\n// Changes on every deploy; see /api/version and components/DeployWatcher.tsx.\nexport const DEPLOY_VERSION = ${JSON.stringify(version)};\n`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, content);
console.log(`[deploy-version] ${version}`);
