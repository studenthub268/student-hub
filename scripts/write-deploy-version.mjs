/**
 * Writes lib/generated/deploy-version.ts before every `next build` (see the
 * build script in package.json):
 *
 *   DEPLOY_VERSION   deploy id — git short SHA (Vercel or local), else timestamp
 *   POLICY_VERSION   app version from package.json — displayed on the terms
 *                    page and recorded with each user's terms acceptance
 *   LAST_UPDATED     commit date of package.json ("September 10, 2026" form),
 *                    else the latest commit date — moves with every release
 *                    without a hand-edited date
 *
 * A release is one `npm version` bump: it commits package.json, which
 * refreshes both POLICY_VERSION and LAST_UPDATED on the next build.
 */
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const outPath = resolve(process.cwd(), "lib/generated/deploy-version.ts");

const git = (cmd) => {
  try {
    return execSync(cmd, { encoding: "utf8" }).trim();
  } catch {
    return null;
  }
};

let deployVersion;
if (process.env.VERCEL_GIT_COMMIT_SHA) {
  deployVersion = process.env.VERCEL_GIT_COMMIT_SHA.slice(0, 12);
} else {
  deployVersion = git("git rev-parse --short=12 HEAD") || `t-${Date.now()}`;
}

const { version } = JSON.parse(readFileSync(resolve(process.cwd(), "package.json"), "utf8"));

const dateSource =
  git("git log -1 --format=%cs -- package.json") || git("git log -1 --format=%cs");
const lastUpdated = dateSource
  ? new Date(dateSource + "T00:00:00Z")
  : new Date();
const LAST_UPDATED = lastUpdated.toLocaleDateString("en-US", {
  month: "long",
  day: "numeric",
  year: "numeric",
  timeZone: "UTC",
});

const content = `// AUTO-GENERATED by scripts/write-deploy-version.mjs — do not edit.
// DEPLOY_VERSION changes on every deploy (see /api/version and
// components/DeployWatcher.tsx); POLICY_VERSION and LAST_UPDATED follow
// package.json version + its last commit date.
export const DEPLOY_VERSION = ${JSON.stringify(deployVersion)};
export const POLICY_VERSION = ${JSON.stringify(version)};
export const LAST_UPDATED = ${JSON.stringify(LAST_UPDATED)};
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, content);

// public/sw.js is served verbatim (not bundled), so its cache names get the
// app version via an idempotent build-time rewrite: whatever version number
// the names currently carry is normalized to package.json's version. The
// file only diffs in git when the version actually changes.
const swPath = resolve(process.cwd(), "public/sw.js");
const swSource = readFileSync(swPath, "utf8");
const sw = swSource.replace(
  /(student-hub-(?:static|dynamic)-)v[\d.]+/g,
  `$1v${version}`
);
if (sw === swSource && swSource.includes("-v" + version) === false)
  throw new Error("sw.js cache-name rewrite failed");
writeFileSync(swPath, sw);

console.log(`[deploy-version] ${deployVersion} · v${version} · ${LAST_UPDATED}`);
